#!/usr/bin/env python3
"""Actual rule generation for the ``block`` and ``block_nat`` chains.

We examine the rules produced by ``Firewall.apply_custom()`` for audit finding
F4. The tests run the real generator but capture script execution, so nft
does not start and the system firewall does not change.

Alongside the earlier test that only checked line counts and a few fragments,
these tests also pin down the full match expression, the verdict (``drop``),
the condition for ``block_nat`` and the transactional behavior of invalid
entries.
"""

from __future__ import annotations

import subprocess
import sys
import types
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import gateway  # noqa: E402

# Cleanup must flush exactly these chains and nothing else.
CUSTOM_CHAINS = (
    "preauth", "preauth_input", "block", "preauth_nat", "block_nat"
)


def valid_preauth_entry() -> dict:
    """Valid pre-auth entry: TCP 8080 from the LAN, without destination."""
    return {"enabled": True, "proto": "tcp", "ports": [8080]}


def valid_block_entry() -> dict:
    """Valid block entry: UDP 53 toward 10.0.0.0/8."""
    return {
        "enabled": True,
        "proto": "udp",
        "ports": [53],
        "dst": "10.0.0.0/8",
    }


class BlockGenerationTestCase(unittest.TestCase):
    """Shared helper: collects the script generated by ``Firewall`` into memory."""

    def setUp(self) -> None:
        self.firewall = gateway.Firewall(
            dry_run=True,
            logger=lambda *_: None,
            lan_if="eth1",
            wan_if="eth0",
        )
        self.table = self.firewall.table
        self.scripts: list[str] = []
        self.run_calls: list[list[str]] = []
        # Instead of real nft/conntrack we only record the calls.
        self.firewall._run_script = self.scripts.append  # type: ignore[method-assign]
        self.firewall._run = self._record_run  # type: ignore[method-assign]

    def _record_run(
        self, args: list[str], check: bool = True
    ) -> subprocess.CompletedProcess:
        self.run_calls.append(list(args))
        return subprocess.CompletedProcess(
            [self.firewall.binary, *args], 0, b"", b""
        )

    def apply_block(self, block: list[dict]) -> list[str]:
        """Install a block set, returning the generated lines."""
        self.scripts.clear()
        self.run_calls.clear()
        self.firewall.apply_custom(block=block)
        self.assertEqual(len(self.scripts), 1, self.scripts)
        self.assertEqual(self.run_calls, [])
        return self.scripts[0].splitlines()

    def chain_lines(self, lines: list[str], chain: str) -> list[str]:
        """Only the ``add rule`` lines for the given chain."""
        prefix = f"add rule inet {self.table} {chain} "
        return [line for line in lines if line.startswith(prefix)]

    def assert_log_then_drop(
        self, lines: list[str], chain: str, match: str
    ) -> None:
        """The log+drop pair for the given match exists exactly once,
        and the logging rule sits directly before the dropping one."""
        prefix = f"add rule inet {self.table} {chain} {match}"
        expected_drop = prefix + " drop"
        logs = [
            line
            for line in lines
            if line.startswith(prefix + " limit rate ")
        ]
        drops = [line for line in lines if line == expected_drop]
        self.assertEqual(len(logs), 1, lines)
        self.assertEqual(len(drops), 1, lines)

        log_line = logs[0]
        self.assertIn("reason=block", log_line)
        self.assertTrue(
            log_line.endswith(f"group {self.firewall.drop_log_group}"),
            log_line,
        )
        self.assertEqual(lines.index(expected_drop), lines.index(log_line) + 1)

        for line in (log_line, expected_drop):
            with self.subTest(line=line):
                # The block rule is interface-independent and never accepts.
                self.assertNotIn("iifname", line)
                self.assertNotIn("oifname", line)
                self.assertNotIn(" accept", line)
                self.assertNotIn(" return", line)
        self.assertTrue(expected_drop.endswith(" drop"))


class ApplyCustomBlockGenerationTests(BlockGenerationTestCase):
    """Exact content of the block rules generated by ``apply_custom()``."""

    def test_tcp_block_without_destination(self) -> None:
        """Without a destination there is no ``ct original ip daddr`` and no ``block_nat``."""
        lines = self.apply_block(
            [{"proto": "tcp", "ports": [80, 443]}]
        )
        match = (
            "meta l4proto tcp "
            "ct original proto-dst { 80, 443 }"
        )
        self.assert_log_then_drop(lines, "block", match)

        block = self.chain_lines(lines, "block")
        self.assertEqual(len(block), 2, block)
        for line in block:
            self.assertNotIn("ct original ip daddr", line)
        self.assertFalse(
            any("ct original ip daddr" in line for line in lines), lines
        )
        # Without a destination the separate pre-portal-redirect block is not made either.
        self.assertEqual(self.chain_lines(lines, "block_nat"), [])

    def test_tcp_block_with_destination(self) -> None:
        """For TCP 80 to a destination, ``block_nat`` is made alongside the normal block."""
        lines = self.apply_block(
            [
                {
                    "dst": "203.0.113.0/24",
                    "proto": "tcp",
                    "ports": [80],
                }
            ]
        )
        match = (
            "meta l4proto tcp "
            "ct original ip daddr 203.0.113.0/24 "
            "ct original proto-dst 80"
        )
        self.assert_log_then_drop(lines, "block", match)
        self.assertEqual(len(self.chain_lines(lines, "block")), 2)

        self.assert_log_then_drop(lines, "block_nat", match)
        self.assertEqual(len(self.chain_lines(lines, "block_nat")), 2)

    def test_udp_block_with_destination(self) -> None:
        """Exact match of a UDP block; ``block_nat`` is never made for UDP."""
        lines = self.apply_block(
            [
                {
                    "dst": "198.51.100.0/24",
                    "proto": "udp",
                    "ports": [53, 123],
                }
            ]
        )
        match = (
            "meta l4proto udp "
            "ct original ip daddr 198.51.100.0/24 "
            "ct original proto-dst { 53, 123 }"
        )
        self.assert_log_then_drop(lines, "block", match)
        self.assertEqual(len(self.chain_lines(lines, "block")), 2)
        self.assertEqual(self.chain_lines(lines, "block_nat"), [])

    def test_multi_port_block_lists_every_port_in_order(self) -> None:
        """With several ports the list contains every port in the given order."""
        lines = self.apply_block(
            [
                {
                    "dst": "192.0.2.7",
                    "proto": "tcp",
                    "ports": [443, 80, 22, 8080],
                }
            ]
        )
        # The host address normalizes to /32 and the port list order is kept.
        match = (
            "meta l4proto tcp "
            "ct original ip daddr 192.0.2.7/32 "
            "ct original proto-dst { 443, 80, 22, 8080 }"
        )
        self.assert_log_then_drop(lines, "block", match)

        # Port 80 is included, so block_nat is made only for port 80.
        nat_match = (
            "meta l4proto tcp "
            "ct original ip daddr 192.0.2.7/32 "
            "ct original proto-dst 80"
        )
        self.assert_log_then_drop(lines, "block_nat", nat_match)
        self.assertEqual(len(self.chain_lines(lines, "block_nat")), 2)

    def test_destination_is_normalized(self) -> None:
        """The given destination is normalized to a CIDR, without surrounding spaces."""
        lines = self.apply_block(
            [
                {
                    "dst": " 203.0.113.77/24 ",
                    "proto": "udp",
                    "ports": [53],
                },
                {"dst": "192.0.2.7", "proto": "tcp", "ports": [443]},
            ]
        )
        script = "\n".join(lines)
        # A network with host bits normalizes to the network address.
        self.assertIn("ct original ip daddr 203.0.113.0/24", script)
        self.assertNotIn("203.0.113.77", script)
        self.assertIn("ct original ip daddr 192.0.2.7/32", script)

    def test_block_nat_only_for_tcp_port_80_with_destination(self) -> None:
        """The condition for ``block_nat``: TCP, port 80 and a given destination."""
        # TCP 80 but without a destination: no block_nat.
        lines = self.apply_block(
            [{"dst": "", "proto": "tcp", "ports": [80]}]
        )
        self.assertEqual(self.chain_lines(lines, "block_nat"), [])

        # TCP 80 with a given destination: block_nat exists, as a log+drop pair.
        lines = self.apply_block(
            [
                {
                    "dst": "203.0.113.0/24",
                    "proto": "tcp",
                    "ports": [80],
                }
            ]
        )
        nat_match = (
            "meta l4proto tcp "
            "ct original ip daddr 203.0.113.0/24 "
            "ct original proto-dst 80"
        )
        self.assert_log_then_drop(lines, "block_nat", nat_match)

        # UDP 80 with a given destination: never any block_nat.
        lines = self.apply_block(
            [
                {
                    "dst": "203.0.113.0/24",
                    "proto": "udp",
                    "ports": [80],
                }
            ]
        )
        self.assertEqual(self.chain_lines(lines, "block_nat"), [])

        # TCP with a given destination but without 80: no block_nat.
        lines = self.apply_block(
            [
                {
                    "dst": "203.0.113.0/24",
                    "proto": "tcp",
                    "ports": [443],
                }
            ]
        )
        self.assertEqual(self.chain_lines(lines, "block_nat"), [])

    def test_block_rules_never_accept_or_return_and_log_precedes_drop(
        self,
    ) -> None:
        """The block chains contain only log+drop pairs, no other verdict."""
        lines = self.apply_block(
            [
                {"dst": "", "proto": "tcp", "ports": [8080]},
                {
                    "dst": "203.0.113.0/24",
                    "proto": "tcp",
                    "ports": [80, 443],
                },
                {
                    "dst": "198.51.100.0/24",
                    "proto": "udp",
                    "ports": [53],
                },
            ]
        )
        for chain in ("block", "block_nat"):
            chain_lines = self.chain_lines(lines, chain)
            self.assertTrue(chain_lines, chain)
            for line in chain_lines:
                with self.subTest(chain=chain, line=line):
                    self.assertNotIn(" accept", line)
                    self.assertNotIn(" return", line)
                    self.assertNotIn("iifname", line)
                    self.assertNotIn("oifname", line)

            logs = [
                line for line in chain_lines if "reason=block" in line
            ]
            drops = [
                line for line in chain_lines if line.endswith(" drop")
            ]
            self.assertEqual(len(logs), len(drops), chain_lines)
            # Every dropping rule is directly preceded by the logging rule
            # with the same match.
            for index, line in enumerate(chain_lines):
                if not line.endswith(" drop"):
                    continue
                self.assertGreater(index, 0, chain_lines)
                log_line = chain_lines[index - 1]
                prefix, separator, _ = log_line.partition(" limit rate ")
                self.assertTrue(separator, log_line)
                self.assertIn("reason=block", log_line)
                self.assertEqual(line, prefix + " drop")


class InvalidBlockEntryTests(BlockGenerationTestCase):
    """With an invalid entry the whole transaction is skipped."""

    INVALID_ENTRIES = (
        # No port.
        {"proto": "tcp", "ports": []},
        {"proto": "tcp"},
        # Not a tcp/udp protocol.
        {"proto": "", "ports": [80]},
        {"proto": "icmp", "ports": [1]},
        {"proto": "sctp", "ports": [80]},
        # Invalid destination CIDR.
        {"dst": "nem-cidr", "proto": "tcp", "ports": [80]},
        {"dst": "999.0.0.0/24", "proto": "tcp", "ports": [80]},
        {"dst": "203.0.113.0/33", "proto": "tcp", "ports": [80]},
        # Invalid port: zero, out of range, non-integer, string.
        {"proto": "tcp", "ports": [0]},
        {"proto": "tcp", "ports": [-1]},
        {"proto": "tcp", "ports": [65536]},
        {"proto": "tcp", "ports": [80.0]},
        {"proto": "tcp", "ports": ["80"]},
        {"proto": "tcp", "ports": None},
        {"proto": "tcp", "ports": "80"},
        # An IPv6 destination cannot be assigned to the IPv4 matcher.
        {"dst": "2001:db8::/32", "proto": "tcp", "ports": [80]},
    )

    def test_invalid_entry_raises_and_runs_no_script(self) -> None:
        """Every invalid entry raises ``FirewallError`` and no nft script runs."""
        for entry in self.INVALID_ENTRIES:
            with self.subTest(entry=entry):
                self.scripts.clear()
                self.run_calls.clear()
                with self.assertRaises(gateway.FirewallError):
                    self.firewall.apply_custom(block=[entry])
                # The generator assembles the whole script first, so on error
                # not a single partial rule reaches nft.
                self.assertEqual(self.scripts, [])
                self.assertEqual(self.run_calls, [])

    def test_invalid_entry_after_valid_one_runs_no_partial_script(self) -> None:
        """An invalid entry after a valid one does not install partially either."""
        self.scripts.clear()
        self.run_calls.clear()
        with self.assertRaises(gateway.FirewallError):
            self.firewall.apply_custom(
                block=[
                    {
                        "dst": "203.0.113.0/24",
                        "proto": "tcp",
                        "ports": [80],
                    },
                    {"dst": "", "proto": "tcp", "ports": []},
                ]
            )
        self.assertEqual(self.scripts, [])
        self.assertEqual(self.run_calls, [])

    def test_invalid_preauth_entry_raises_and_runs_no_script(self) -> None:
        """The pre-auth branch uses the same strict validation."""
        for entry in (
            {"dst": "2001:db8::/32", "proto": "tcp", "ports": [80]},
            {"proto": "tcp", "ports": [0]},
            {"proto": "tcp", "ports": ["80"]},
        ):
            with self.subTest(entry=entry):
                self.scripts.clear()
                self.run_calls.clear()
                with self.assertRaises(gateway.FirewallError):
                    self.firewall.apply_custom(preauth=[entry])
                self.assertEqual(self.scripts, [])
                self.assertEqual(self.run_calls, [])


class ClearCustomTests(BlockGenerationTestCase):
    """``clear_custom()`` flushes only the five custom chains."""

    def test_clear_custom_flushes_exactly_the_custom_chains(self) -> None:
        """Five ``add chain`` and five ``flush chain``, with no other side effect."""
        self.scripts.clear()
        self.run_calls.clear()
        self.firewall.clear_custom()

        self.assertEqual(len(self.scripts), 1, self.scripts)
        lines = [
            line for line in self.scripts[0].splitlines() if line.strip()
        ]
        expected = [
            f"add chain inet {self.table} {chain}"
            for chain in CUSTOM_CHAINS
        ] + [
            f"flush chain inet {self.table} {chain}"
            for chain in CUSTOM_CHAINS
        ]
        self.assertEqual(lines, expected)

        # We do not touch the session sets or conntrack.
        self.assertEqual(self.run_calls, [])
        script = "\n".join(lines)
        for token in (
            "conntrack",
            "flush set",
            "delete element",
            "allowed_tcp",
            "allowed_udp",
            "allowed_input_tcp",
            "allowed_input_udp",
            "allowed_icmp",
            "host_service_tcp",
            "host_service_udp",
            "banned_v4",
            "client_mac",
            "@",
        ):
            with self.subTest(token=token):
                self.assertNotIn(token, script)

        # Every chain appears exactly once in add and once in flush form.
        self.assertEqual(len(lines), 2 * len(CUSTOM_CHAINS))
        for chain in CUSTOM_CHAINS:
            hits = [
                line for line in lines if line.endswith(f" {chain}")
            ]
            self.assertEqual(len(hits), 2, (chain, hits))


class ReplaceCustomTests(BlockGenerationTestCase):
    """``replace_custom()`` replaces in a single nft transaction (F11)."""

    def test_replace_custom_is_one_transaction(self) -> None:
        """Chain creation, flush and the new rules in a single script."""
        self.scripts.clear()
        self.run_calls.clear()
        self.firewall.replace_custom(
            preauth=[valid_preauth_entry()],
            block=[valid_block_entry()],
        )

        # Exactly one nft call: no separate clear_custom()/_run() before
        # or after, so there is no intermediate state where the old
        # rules are already gone but the new ones are not yet in effect.
        self.assertEqual(len(self.scripts), 1, self.scripts)
        self.assertEqual(self.run_calls, [])

        lines = self.scripts[0].splitlines()
        for chain in CUSTOM_CHAINS:
            with self.subTest(chain=chain):
                self.assertIn(
                    f"add chain inet {self.table} {chain}", lines
                )
                self.assertIn(
                    f"flush chain inet {self.table} {chain}", lines
                )

        # The generated pre-auth and block rules are in the same script,
        # not in separate transactions.
        preauth_rule = (
            f'add rule inet {self.table} preauth iifname "eth1" '
            "meta l4proto tcp ct original proto-dst 8080 "
            f"meta mark set {self.firewall.fwd_mark} accept"
        )
        block_drop = (
            f"add rule inet {self.table} block meta l4proto udp "
            "ct original ip daddr 10.0.0.0/8 "
            "ct original proto-dst 53 drop"
        )
        self.assertIn(preauth_rule, lines)
        self.assertIn(block_drop, lines)

    def test_replace_custom_render_error_runs_nothing(self) -> None:
        """With an invalid entry rendering fails and nft does not start."""
        self.scripts.clear()
        self.run_calls.clear()

        with self.assertRaises(gateway.FirewallError):
            self.firewall.replace_custom(
                block=[{"proto": "tcp", "ports": [0]}]
            )

        # The whole script is assembled before execution, so on error
        # not a single partial rule reaches nft.
        self.assertEqual(self.scripts, [])
        self.assertEqual(self.run_calls, [])

    def test_replace_custom_keep_block_preserves_block_chains(self) -> None:
        """``keep_block=True``: only the pre-auth chains are replaced."""
        self.scripts.clear()
        self.run_calls.clear()
        self.firewall.replace_custom(
            preauth=[valid_preauth_entry()],
            block=[valid_block_entry()],
            keep_block=True,
        )

        self.assertEqual(len(self.scripts), 1, self.scripts)
        self.assertEqual(self.run_calls, [])
        lines = self.scripts[0].splitlines()

        for chain in ("preauth", "preauth_input", "preauth_nat"):
            with self.subTest(chain=chain):
                self.assertIn(
                    f"add chain inet {self.table} {chain}", lines
                )
                self.assertIn(
                    f"flush chain inet {self.table} {chain}", lines
                )

        preauth_rule = (
            f'add rule inet {self.table} preauth iifname "eth1" '
            "meta l4proto tcp ct original proto-dst 8080 "
            f"meta mark set {self.firewall.fwd_mark} accept"
        )
        self.assertIn(preauth_rule, lines)

        # We do not touch the block chains at all: neither creation, nor
        # flush, nor any rule may appear for them. We check the exact lines
        # so that another occurrence of the word "block" (e.g. in an
        # explanatory text) does not produce a false hit.
        for chain in ("block", "block_nat"):
            prefix = f"add rule inet {self.table} {chain} "
            with self.subTest(chain=chain):
                self.assertNotIn(
                    f"add chain inet {self.table} {chain}", lines
                )
                self.assertNotIn(
                    f"flush chain inet {self.table} {chain}", lines
                )
                self.assertFalse(
                    any(line.startswith(prefix) for line in lines), lines
                )
                self.assertEqual(self.chain_lines(lines, chain), [])
        self.assertNotIn("reason=block", self.scripts[0])


class ApplyCustomSettingsTests(BlockGenerationTestCase):
    """``Gateway._apply_custom_settings()`` with a corrupt snapshot."""

    def test_apply_custom_settings_corrupt_snapshot_keeps_block(self) -> None:
        """On invalid settings pre-auth is flushed while the block chains remain."""
        self.scripts.clear()
        self.run_calls.clear()
        audit_calls: list[tuple[str, dict]] = []

        # Minimal fake Gateway: only the firewall and audit logging are
        # needed; the snapshot is passed directly, so no
        # settings/store is required.
        fake = types.SimpleNamespace()
        fake.firewall = self.firewall
        fake._write_audit = lambda event, **fields: audit_calls.append(
            (event, fields)
        )

        gateway.Gateway._apply_custom_settings(
            fake,
            {
                "error": "simulated error",
                "preauth": [valid_preauth_entry()],
                "block": [valid_block_entry()],
            },
        )

        self.assertEqual(len(self.scripts), 1, self.scripts)
        self.assertEqual(self.run_calls, [])
        lines = self.scripts[0].splitlines()

        # It replaces only the pre-auth chains; the last known good content
        # of the block/block_nat chains stays in the kernel.
        for chain in ("preauth", "preauth_input", "preauth_nat"):
            with self.subTest(chain=chain):
                self.assertIn(
                    f"add chain inet {self.table} {chain}", lines
                )
                self.assertIn(
                    f"flush chain inet {self.table} {chain}", lines
                )
        for chain in ("block", "block_nat"):
            prefix = f"add rule inet {self.table} {chain} "
            with self.subTest(chain=chain):
                self.assertNotIn(
                    f"add chain inet {self.table} {chain}", lines
                )
                self.assertNotIn(
                    f"flush chain inet {self.table} {chain}", lines
                )
                self.assertFalse(
                    any(line.startswith(prefix) for line in lines), lines
                )
        self.assertEqual(self.chain_lines(lines, "block"), [])
        self.assertEqual(self.chain_lines(lines, "block_nat"), [])

        # Fail-closed: no pre-auth entry from the corrupt snapshot may be
        # installed; only the always-present banned-source guard rule
        # remains in the (flushed) preauth chain.
        self.assertEqual(
            self.chain_lines(lines, "preauth"),
            [
                f"add rule inet {self.table} preauth "
                f"ip saddr @{self.firewall.ban_set} drop"
            ],
        )
        self.assertNotIn("8080", self.scripts[0])

        # The corrupt settings must be audited so the error can be noticed,
        # and the entry must contain the exact reason.
        self.assertEqual(
            [event for event, _fields in audit_calls],
            ["settings_invalid"],
        )
        self.assertEqual(
            audit_calls[0][1], {"reason": "simulated error"}
        )


